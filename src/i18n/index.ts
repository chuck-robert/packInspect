const DICTS: Record<Locale, Dict> = { 'zh-CN': zhCN, 'en-US': enUS }

/** 取当前语言下的文案；缺失时回退到中文，再回退到 key 本身 */
export function translate(locale: Locale, key: string, params?: Record<string, string | number>): string {
  const raw = DICTS[locale]?.[key] ?? zhCN[key] ?? key
  if (!params) return raw
  return raw.replace(/\{(\w+)\}/g, (_, name: string) =>
    params[name] === undefined ? `{${name}}` : String(params[name]),
  )
}

/** 组合式：在组件里 `const { t, locale } = useI18n()` */
export function useI18n() {
  const settings = useSettingsStore()
  const locale = computed<Locale>(() => (settings.settings.language === 'en-US' ? 'en-US' : 'zh-CN'))
  const t = (key: string, params?: Record<string, string | number>) => translate(locale.value, key, params)
  return { t, locale }
}

/** 供非组件环境（例如 store）使用 */
export function currentLocale(): Locale {
  try {
    const settings = useSettingsStore()
    return settings.settings.language === 'en-US' ? 'en-US' : 'zh-CN'
  } catch {
    return 'zh-CN'
  }
}
